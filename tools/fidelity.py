"""Fidelity ledger: every GoatGame UnrealScript class vs. the Rust port.

A class counts as "referenced" when the Rust sources mention it (we cite the original class and
function names in comments wherever behaviour is ported). Functions of referenced classes are
checked the same way, so the ledger shows how much of each class is covered.

usage: python -I tools/fidelity.py   -> Docs/FIDELITY.md
"""
import collections
import os
import re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
scripts = os.path.join(root, 'out', 'scripts', 'GoatGame')
rust = ''
for d in ('goat/src', 'upk/src'):
    for dp, _, fs in os.walk(os.path.join(root, d)):
        for f in fs:
            if f.endswith('.rs'):
                rust += open(os.path.join(dp, f), encoding='utf-8').read() + '\n'

fn_re = re.compile(r'^\s*(?:[\w()]+\s+)*?(?:function|event)\s+(?:[\w<>]+\s+)?(\w+)\s*\(', re.M)
cls_re = re.compile(r'^class\s+(\w+)\s+extends\s+(\w+)', re.M)

classes = {}
for f in sorted(os.listdir(scripts)):
    if not f.endswith('.uc'):
        continue
    src = open(os.path.join(scripts, f), encoding='utf-8', errors='replace').read()
    m = cls_re.search(src)
    parent = m.group(2) if m else '?'
    fns = sorted(set(fn_re.findall(src)))
    classes[f[:-3]] = (parent, src.count('\n'), fns)


def category(name, parent):
    chain = [name]
    p = parent
    while p in classes and len(chain) < 12:
        chain.append(p)
        p = classes[p][0]
    chain.append(p)
    s = ' '.join(chain)
    for key, cat in [
        ('GIAG', 'Arcade mini-games (GIAG)'),
        ('GGUI', 'Menus / UI (Scaleform)'),
        ('GGHUD', 'Menus / UI (Scaleform)'),
        ('GFx', 'Menus / UI (Scaleform)'),
        ('Quest', 'Quests / achievements'),
        ('Achievement', 'Quests / achievements'),
        ('Mutator', 'Mutators (goat abilities)'),
        ('GGSeq', 'Kismet (level scripting)'),
        ('Sequence', 'Kismet (level scripting)'),
        ('Trick', 'Tricks / score'),
        ('Combo', 'Tricks / score'),
        ('Vehicle', 'Vehicles'),
        ('GGSVehicle', 'Vehicles'),
        ('Bicycle', 'Vehicles'),
        ('Longboard', 'Vehicles'),
        ('AIController', 'NPCs / AI'),
        ('GGNpc', 'NPCs / AI'),
        ('GGGoat', 'Goat'),
        ('GGPawn', 'Goat'),
        ('PlayerController', 'Player / camera / input'),
        ('PlayerInput', 'Player / camera / input'),
        ('Camera', 'Player / camera / input'),
        ('GameInfo', 'Game modes'),
        ('KActor', 'Props / physics actors'),
        ('InterpActor', 'Props / physics actors'),
        ('Apex', 'Props / physics actors'),
        ('Explosive', 'Props / physics actors'),
        ('DamageType', 'Props / physics actors'),
        ('Volume', 'Volumes / triggers'),
        ('Trigger', 'Volumes / triggers'),
        ('PlayerStart', 'Spawning'),
        ('SpawnPoint', 'Spawning'),
    ]:
        if key in s:
            return cat
    return 'Other'


def mentioned(word):
    return re.search(r'\b' + re.escape(word) + r'\b', rust) is not None


by_cat = collections.defaultdict(list)
for name, (parent, lines, fns) in classes.items():
    cov = [f for f in fns if mentioned(f)] if mentioned(name) else []
    by_cat[category(name, parent)].append((name, parent, lines, fns, mentioned(name), cov))

total_lines = sum(c[1] for c in classes.values())
ref_lines = sum(c[2] for cat in by_cat.values() for c in cat if c[4])
out = [f'# Fidelity ledger (generated by tools/fidelity.py)\n',
       f'GoatGame.u: {len(classes)} classes, {total_lines} lines of UnrealScript. Classes the Rust port '
       f'references: {sum(1 for cat in by_cat.values() for c in cat if c[4])} ({ref_lines} lines).\n',
       'A class is "referenced" when the Rust code cites it; "functions" counts its functions/events the '
       'Rust code cites by name (a rough measure: helpers are often folded into other code).\n']
order = sorted(by_cat, key=lambda k: -sum(c[2] for c in by_cat[k]))
out.append('| Area | Classes | Referenced | Lines | Lines referenced |\n|---|---|---|---|---|')
for cat in order:
    cs = by_cat[cat]
    out.append(f'| {cat} | {len(cs)} | {sum(1 for c in cs if c[4])} | {sum(c[2] for c in cs)} | {sum(c[2] for c in cs if c[4])} |')
for cat in order:
    out.append(f'\n## {cat}\n')
    out.append('| Class | Extends | Lines | Status | Functions cited |\n|---|---|---|---|---|')
    for name, parent, lines, fns, ref, cov in sorted(by_cat[cat], key=lambda c: -c[2]):
        status = 'referenced' if ref else 'missing'
        out.append(f'| {name} | {parent} | {lines} | {status} | {len(cov)}/{len(fns)} |')
path = os.path.join(root, 'Docs', 'FIDELITY.md')
open(path, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('\n'.join(out[:3 + 2 + len(order)]))
